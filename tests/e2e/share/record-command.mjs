import { spawn, spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync, openSync, closeSync } from 'node:fs'
import { resolve, join, dirname } from 'node:path'
import { createHash } from 'node:crypto'

const mode = process.argv[2], windows = process.platform === 'win32'
const commands = {
  unit: ['corepack', 'pnpm', '--filter', '@codeless/web', 'exec', 'vitest', 'run', 'src/features/source', 'src/features/deploy'],
  screenshot: ['node', '--test', 'tests/e2e/share/screenshot.acceptance.mjs'],
  browser: ['corepack', 'pnpm', '--filter', '@codeless/web', 'exec', 'playwright', 'test', '--config', 'playwright.config.ts', 'share/flow.spec.ts'],
  static: ['corepack', 'pnpm', 'verify:static'], api: ['corepack', 'pnpm', 'verify:api'],
  runner: ['corepack', 'pnpm', 'verify:runner'], e2e: ['corepack', 'pnpm', 'verify:e2e'], gate: ['corepack', 'pnpm', 'ci:gate'],
}
if (!Object.hasOwn(commands, mode)) throw new Error('unknown recording mode')
const directory = resolve('.local-data/d16-b', new Date().toISOString().replaceAll(':', '-') + '-' + mode)
mkdirSync(directory, { recursive: true })
const env = { ...process.env, CODELESS_MODEL_PROVIDER: 'deterministic-mock', CODELESS_SHARE_EVIDENCE_DIR: join(directory, 'screenshot') }
delete env.CODELESS_MODEL_API_KEY; delete env.CODELESS_MODEL_NAME; delete env.CODELESS_PLAYWRIGHT_CHANNEL; delete env.VITE_PUBLICATION_ORIGIN
if (windows) {
  const pathKey = Object.keys(env).find(key => key.toUpperCase() === 'PATH'), previous = env[pathKey] ?? ''
  for (const key of Object.keys(env)) if (key.toUpperCase() === 'PATH') delete env[key]
  env.PATH = resolve('.local-data/d13-b/bin') + ';' + dirname(process.execPath) + ';' + (env.JAVA_HOME ? env.JAVA_HOME + '/bin;' : '') + previous
}
const metadata = { mode, command: commands[mode], startedAt: new Date().toISOString(), status: 'RUNNING', exitCode: null, signal: null,
  head: spawnSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).stdout.trim(),
  changes: spawnSync('git', ['status', '--porcelain'], { encoding: 'utf8' }).stdout.trim() }
metadata.toolchain = { node: process.version, javaHome: env.JAVA_HOME ?? null, pnpm: '12.6.0 (repository corepack pin)' }
const sourcePaths = spawnSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z', '--',
  'services/runner/src/screenshot', 'apps/web/src/features/deploy', 'apps/web/src/features/source', 'tests/e2e/share'],
  { encoding: 'utf8' }).stdout.split('\0').filter(Boolean)
metadata.sourceDigests = Object.fromEntries([...new Set(sourcePaths)].filter(path => !path.includes('/evidence/')).map(path => {
  const bytes = readFileSync(path)
  return [path, { bytes: bytes.length, digest: 'sha256:' + createHash('sha256').update(bytes).digest('hex'),
    lfDigest: 'sha256:' + createHash('sha256').update(bytes.toString('utf8').replaceAll('\r\n', '\n')).digest('hex') }]
}))
// Existing suites regenerate their historical tracked evidence. Preserve original
// bytes and retain generated bytes privately, following the D15 recording pattern.
const originals = new Map()
if (['api', 'e2e', 'gate'].includes(mode)) {
  const paths = spawnSync('git', ['ls-files', '-z'], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }).stdout.split('\0')
    .filter(path => path.includes('/evidence/') && !path.startsWith('tests/e2e/share/'))
  for (const path of paths) originals.set(path, readFileSync(path))
}
const save = () => writeFileSync(join(directory, 'run.json'), JSON.stringify(metadata, null, 2))
save(); console.log(JSON.stringify({ directory, status: 'RUNNING' }))
const fd = openSync(join(directory, 'command.log'), 'wx')
const child = spawn(windows ? process.env.ComSpec : commands[mode][0], windows ? ['/d', '/c', ...commands[mode]] : commands[mode].slice(1),
  { env, windowsHide: true, stdio: ['ignore', fd, fd] })
child.once('error', error => { metadata.launchError = error.message })
child.once('close', (exitCode, signal) => {
  closeSync(fd); metadata.generatedHistoricalEvidence = []
  for (const [path, original] of originals) {
    const generated = readFileSync(path)
    if (generated.equals(original)) continue
    const destination = join(directory, 'generated-history', path)
    mkdirSync(dirname(destination), { recursive: true }); writeFileSync(destination, generated)
    writeFileSync(path, original); metadata.generatedHistoricalEvidence.push(path)
  }
  Object.assign(metadata, { exitCode, signal, completedAt: new Date().toISOString(), status: exitCode === 0 && signal === null ? 'PASSED' : 'FAILED',
    logDigest: 'sha256:' + createHash('sha256').update(readFileSync(join(directory, 'command.log'))).digest('hex') })
  save(); console.log(JSON.stringify({ directory, mode, exitCode, signal, status: metadata.status, logDigest: metadata.logDigest })); process.exitCode = exitCode === 0 && signal === null ? 0 : exitCode || 1
})
